#!/bin/sh
# Initialization of directories and local configuration.
# This file is included from lar.sh.

if [ "${0##*/}" = "bootstrap.sh" ]; then
  printf '%s\n' "This file is loaded from ./lar.sh" >&2
  exit 1
fi

lar_require_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    lar_fail "docker was not found. Install Docker Engine or Docker Desktop."
  fi
  if ! docker compose version >/dev/null 2>&1; then
    lar_fail "Docker Compose v2 was not found. The command is required: docker compose"
  fi
  if ! docker info >/dev/null 2>&1; then
    lar_fail "Docker is installed, but the daemon is not responding. Start Docker and run ./lar.sh init again."
  fi
  printf '%s\n' "  Docker and Compose v2: available"
}

lar_init_dirs() {
  root=$1
  for dir in \
    config \
    config/services \
    config/sites \
    config/nginx \
    config/proxy \
    config/php \
    mysql57 \
    mysql8 \
    mariadb1011 \
    mariadb101 \
    elasticsearch \
    minio \
    redis \
    mailpit \
    certs \
    logs/apache \
    logs/nginx \
    logs/proxy \
    logs/php \
    backups
  do
    mkdir -p "$root/data/$dir"
    if [ ! -e "$root/data/$dir/.gitkeep" ]; then
      : > "$root/data/$dir/.gitkeep"
    fi
  done
  printf '%s\n' "  data directories: ready"
}

lar_init_copy() {
  dest=$1
  src=$2
  label=$3
  overwrite=$4
  if [ ! -f "$src" ]; then
    lar_fail "Missing template: $src"
  fi
  if [ -e "$dest" ] && [ ! -f "$dest" ]; then
    lar_fail "$label exists and is not a file."
  fi
  replaced=0
  if [ -s "$dest" ]; then
    if [ "$overwrite" != 1 ]; then
      printf '%s\n' "  kept $label"
      return 0
    fi
    replaced=1
  fi
  mkdir -p "$(dirname "$dest")"
  cp "$src" "$dest"
  if [ "$replaced" = 1 ]; then
    printf '%s\n' "  replaced $label"
  else
    printf '%s\n' "  created $label"
  fi
}

lar_init_env() {
  root=$1
  overwrite=$2
  dest=$root/data/.env
  if [ -e "$dest" ] && [ ! -f "$dest" ]; then
    lar_fail "data/.env exists and is not a file."
  fi
  replaced=0
  if [ -s "$dest" ]; then
    if [ "$overwrite" != 1 ]; then
      printf '%s\n' "  kept data/.env"
      return 0
    fi
    replaced=1
  fi

  old_umask=$(umask)
  umask 077
  cat > "$dest" <<EOF
# Generated by ./lar.sh init. Not versioned.
# init does not overwrite this file when it already has content.
# Local MySQL: root user, password toor. No database is created.
# MinIO: user minioadmin, password minioadmin. The API uses port 9000 and the console uses 9001.
MYSQL57_ROOT_PASSWORD=toor
MYSQL8_ROOT_PASSWORD=toor
MARIADB1011_ROOT_PASSWORD=toor
MARIADB101_ROOT_PASSWORD=toor
MINIO_ROOT_USER=minioadmin
MINIO_ROOT_PASSWORD=minioadmin
EOF
  umask "$old_umask"
  chmod 600 "$dest"
  if [ "$replaced" = 1 ]; then
    printf '%s\n' "  replaced data/.env"
  else
    printf '%s\n' "  created data/.env"
  fi
}

lar_env_has_key() {
  file=$1
  key=$2
  [ -f "$file" ] || return 1
  awk -F= -v k="$key" '$1 == k { found = 1 } END { exit found ? 0 : 1 }' "$file"
}

lar_env_ensure() {
  key=$1
  value=$2
  file=$LAR_ROOT/data/.env
  if lar_env_has_key "$file" "$key"; then
    return 0
  fi
  last=$(tail -c 1 "$file" 2>/dev/null | od -An -tu1 | tr -d ' ')
  if [ -n "$last" ] && [ "$last" != "10" ]; then
    printf '\n' >> "$file"
  fi
  printf '%s=%s\n' "$key" "$value" >> "$file"
  printf '%s\n' "  data/.env: added $key"
}

lar_copy_if_empty() {
  dest=$1
  src=$2
  label=$3
  if [ -s "$dest" ]; then
    return 0
  fi
  if [ -e "$dest" ] && [ ! -f "$dest" ]; then
    lar_fail "$label exists and is not a file."
  fi
  if [ ! -f "$src" ]; then
    lar_fail "Missing template: $src"
  fi
  mkdir -p "$(dirname "$dest")"
  cp "$src" "$dest"
  printf '%s\n' "  created $label"
}

lar_ensure_service_configs() {
  root=$1
  for dir in mysql8 mariadb1011 mariadb101 elasticsearch minio \
    config/mysql8 config/mariadb1011 config/mariadb101
  do
    mkdir -p "$root/data/$dir"
    if [ ! -e "$root/data/$dir/.gitkeep" ]; then
      : > "$root/data/$dir/.gitkeep"
    fi
  done
  lar_copy_if_empty \
    "$root/data/config/apache/apache.conf" \
    "$root/core/apache/conf/lar.conf" \
    "data/config/apache/apache.conf"
  lar_copy_if_empty \
    "$root/data/config/redis/redis.conf" \
    "$root/core/redis/redis.conf" \
    "data/config/redis/redis.conf"
  lar_copy_if_empty \
    "$root/data/config/mysql57/mysql.cnf" \
    "$root/core/mysql57/mysql.cnf" \
    "data/config/mysql57/mysql.cnf"
  lar_copy_if_empty \
    "$root/data/config/mysql8/mysql.cnf" \
    "$root/core/mysql8/mysql.cnf" \
    "data/config/mysql8/mysql.cnf"
  lar_copy_if_empty \
    "$root/data/config/mariadb1011/mariadb.cnf" \
    "$root/core/mariadb1011/mariadb.cnf" \
    "data/config/mariadb1011/mariadb.cnf"
  lar_copy_if_empty \
    "$root/data/config/mariadb101/mariadb.cnf" \
    "$root/core/mariadb101/mariadb.cnf" \
    "data/config/mariadb101/mariadb.cnf"
  lar_copy_if_empty \
    "$root/data/config/mailpit.env" \
    "$root/core/mailpit/mailpit.env" \
    "data/config/mailpit.env"
  while read -r version ignored; do
    case "$version" in
      ''|\#*)
        continue
        ;;
    esac
    lar_copy_if_empty \
      "$root/data/config/php/${version}/php.ini" \
      "$root/core/php/${version}/php.ini" \
      "data/config/php/${version}/php.ini"
  done < "$root/core/php/versions"
}

lar_init() {
  root=$1
  overwrite=${2:-0}
  printf '%s\n' "Initializing LAR"
  lar_require_docker
  lar_init_dirs "$root"
  lar_init_copy \
    "$root/data/config/settings.yaml" \
    "$root/core/templates/settings.yaml" \
    "data/config/settings.yaml" \
    "$overwrite"
  lar_init_copy \
    "$root/data/config/sites.yaml" \
    "$root/core/templates/sites.yaml" \
    "data/config/sites.yaml" \
    "$overwrite"
  lar_init_env "$root" "$overwrite"
  lar_ensure_service_configs "$root"
  lar_config_load "$root/data/config/settings.yaml"
  printf '%s\n' "  configuration: valid (timezone $LAR_TIMEZONE, default bind $LAR_DEFAULT_BIND)"
  printf '%s\n' "Init finished. To start the enabled services: ./lar.sh up"
}
